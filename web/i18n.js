/** 'en-US' -> 'en'; anything that is not English -> 'es' (the default). */
export function langOf(tag) {
  return /^en\b/i.test(String(tag || '')) ? 'en' : 'es';
}

/** The text table for [lang]; a copy, so a screen can never change it for the others. */
export function strings(lang) {
  return Object.assign({}, langOf(lang) === 'en' ? EN : ES);
}

/** 'Temporada {n}' + {n: 2} -> 'Temporada 2'. A place with no value stays as it is. */
export function fmt(text, values) {
  return String(text).replace(/\{(\w+)\}/g, (m, k) => (values && values[k] !== undefined && values[k] !== null ? String(values[k]) : m));
}
